/* ── 장면 재생 ── */
function storyWho(w) {
  if (w === "nar") return { n: "이야기" };
  if (w === "me") return { n: "나" };
  if (w === "pet") return { n: save.pet ? save.pet.name : "작은 별짐승" };
  if (w === "mentor") return { n: D[MENTOR_OF[save.job || "knight"]].n };
  if (w === "nox") return { n: "녹스" };
  return { n: (D[w] && D[w].n) || w };
}
function storyText(t) {
  if (typeof t === "object") t = t[save.job || "knight"];
  const pn = save.pet ? save.pet.name : "작은 별짐승";
  return t.replace(/\{pet\}이\(가\)/g, jo(pn, "이", "가")).replace(/\{pet\}/g, pn);
}
function playScene(lines, done) {
  const kai = save.st.kai || "cool";
  const L = lines.filter((l) => !l[2] || l[2] === kai);
  const step = (i) => {
    if (i >= L.length) return done && done();
    let j = i;
    const who = L[i][0],
      txt = [];
    while (j < L.length && L[j][0] === who) txt.push(storyText(L[j++][1]));
    openDlg(storyWho(who), txt, () => step(j));
  };
  step(0);
}
function storyOnce(key, lines, done) {
  if (save.st[key] || !lines) return false;
  save.st[key] = 1;
  store();
  playScene(lines, done);
  return true;
}
/* 맵 첫 방문 */
function storyEnter(id) {
  if (!SC[id] || save.st["in_" + id]) return;
  setTimeout(() => {
    if (busy) return;
    storyOnce("in_" + id, SC[id]);
  }, 500);
}
/* 핵심 자리 보스 직전: 장면을 보여 준 뒤 go() 로 전투 시작 */
function storyBoss(pi, go) {
  if (busy || !storyOnce("boss_" + pi, SC_BOSS[pi], go)) go();
}
/* 마을을 모두 되살림 */
function storyPartDone(pi) {
  if (busy) return setTimeout(() => storyPartDone(pi), 800);
  storyOnce("done_" + pi, SC_DONE[pi]);
}
